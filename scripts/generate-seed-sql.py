#!/usr/bin/env python3
"""
Generates a seed SQL file for the negotiator-link load test. Called from scripts/load-test.py

Usage:
  python3 scripts/generate-seed-sql.py [--count N] [--seed-offset K] [--out scripts/load-seed.sql]
"""

import argparse
import sys

PREFIX = "550e8400-e29b-41d4-a716-"
NEG_BASE = 0x667700000000
POST_BASE = 0x667800000000
LIFECYCLE_ID_BASE = 100000
RES_LIFECYCLE_ID_BASE = 200000
STRIDE = 1_000_000

SE_890_CLIENT_PERSON_ID = 10000
CZ_MMCI_CLIENT_PERSON_ID = 10001
RESOURCE_DEFS = [
    (2351, "Load-test collection 1", "Load-test SE_890 collection 1",
     "bbmri-eric:ID:SE_890:collection:lts_dummy_collection_1", 1, 1, 1, SE_890_CLIENT_PERSON_ID),
    (2352, "Load-test collection 2", "Load-test CZ_MMCI collection 1",
     "bbmri-eric:ID:CZ_MMCI:collection:LTS_collection_1", 1, 3, 2, CZ_MMCI_CLIENT_PERSON_ID),
    (2353, "Load-test collection 3", "Load-test CZ_MMCI collection 2",
     "bbmri-eric:ID:CZ_MMCI:collection:LTS_collection_2", 1, 3, 2, CZ_MMCI_CLIENT_PERSON_ID),
    (2354, "Load-test collection 4", "Load-test SE_890 collection 2",
     "bbmri-eric:ID:SE_890:collection:lts_dummy_collection_2", 1, 1, 1, SE_890_CLIENT_PERSON_ID),
]

RESOURCES = [rid for rid, *_ in RESOURCE_DEFS]

REPRESENTATIVE_PERSON_ID = 2

NEGOTIATION_PAYLOAD = (
    '{"project":{"title":"Load Test Negotiation %(i)d",'
    '"disease-code":"Q87.1",'
    '"objective":"Synthetic negotiation generated for load testing",'
    '"organization":"University Medical Center","profit":"No",'
    '"acknowledgment":"Load test","Multichoice test":["first_choice","second_choice"],'
    '"Single test":"first_choice","Bool test":"Yes"},'
    '"request":{"description":"Synthetic load-test request","collection":"",'
    '"donors":"250","samples":"blood","specifics":"n/a"},'
    '"ethics-vote":{"ethics-vote":"Approved","ethics-vote-attachment":null}}'
)


def neg_uuid(i: int, offset: int) -> str:
    return f"{PREFIX}{NEG_BASE + offset * STRIDE + i:012x}"


def post_uuid(i: int, slot: int, offset: int) -> str:
    return f"{PREFIX}{POST_BASE + offset * STRIDE * 2 + i * 2 + slot:012x}"


def generate(count: int, offset: int) -> tuple[str, list[str]]:
    neg_ids = [neg_uuid(i, offset) for i in range(count)]
    lifecycle_base = LIFECYCLE_ID_BASE + offset * STRIDE * 8
    res_lifecycle_base = RES_LIFECYCLE_ID_BASE + offset * STRIDE * 8
    out: list[str] = []
    w = out.append

    w("-- Generated by scripts/generate-seed-sql.py — DO NOT EDIT BY HAND.")
    w(f"-- {count} IN_PROGRESS negotiations (seed-offset {offset}), resources 2351-2354 all REPRESENTATIVE_CONTACTED.")
    w("-- NEGOTIATION_IDS: " + ",".join(neg_ids))
    w("")
    w("\\c negotiator")
    w("")

    # ---- resources 2351-2354 created here ----
    w("-- Load-test resources (2351-2354). All four are created here so the seed does not")
    w("-- depend on any resource already present in the Negotiator dev DB. Each resource links")
    w("-- its org's API-client person (10000 SE_890 / 10001 CZ_MMCI) so APPROVE is authorized.")
    for rid, name, desc, source_id, discovery_id, access_form_id, org_id, client_person_id in RESOURCE_DEFS:
        w("INSERT INTO resource (id, name, description, source_id, discovery_service_id, access_form_id, organization_id)")
        w(f"VALUES ({rid}, '{name}', '{desc}',")
        w(f"        '{source_id}', {discovery_id}, {access_form_id}, {org_id})")
        w("ON CONFLICT DO NOTHING;")
        w(f"INSERT INTO resource_representative_link (resource_id, person_id) "
          f"VALUES ({rid}, {REPRESENTATIVE_PERSON_ID}) ON CONFLICT DO NOTHING;")
        w(f"INSERT INTO resource_representative_link (resource_id, person_id) "
          f"VALUES ({rid}, {client_person_id}) ON CONFLICT DO NOTHING;")
    w("")

    # ---- negotiation ----
    w("-- negotiation (IN_PROGRESS)")
    w("INSERT INTO negotiation (id, creation_date, modified_date, current_state, payload, public_posts_enabled, private_posts_enabled, created_by, modified_by, human_readable, discovery_service_id)")
    w("VALUES")
    rows = []
    for i in range(count):
        payload = NEGOTIATION_PAYLOAD % {"i": i}
        rows.append(
            f"  ('{neg_uuid(i, offset)}', '2024-02-01 09:00:00', '2024-02-01 11:00:00', 'IN_PROGRESS', "
            f"'{payload}', true, true, 1, 1, "
            f"'((diagnosis EQUALS Q87.1) AND (sample_type EQUALS blood))', 1)"
        )
    w(",\n".join(rows))
    w("ON CONFLICT DO NOTHING;")
    w("")

    # ---- negotiation_lifecycle_record (DRAFT -> SUBMITTED -> IN_PROGRESS) ----
    w("-- negotiation_lifecycle_record")
    w("INSERT INTO negotiation_lifecycle_record (id, creation_date, modified_date, created_by, modified_by, changed_to, negotiation_id)")
    w("VALUES")
    rows = []
    for i in range(count):
        base = lifecycle_base + i * 8
        nid = neg_uuid(i, offset)
        rows.append(f"  ({base + 0}, '2024-02-01 08:00:00', '2024-02-01 08:00:00', 1, 1, 'DRAFT',       '{nid}')")
        rows.append(f"  ({base + 1}, '2024-02-01 09:00:00', '2024-02-01 09:00:00', 1, 1, 'SUBMITTED',   '{nid}')")
        rows.append(f"  ({base + 2}, '2024-02-01 11:00:00', '2024-02-01 11:00:00', 2, 2, 'IN_PROGRESS', '{nid}')")
    w(",\n".join(rows))
    w("ON CONFLICT DO NOTHING;")
    w("SELECT setval(pg_get_serial_sequence('negotiation_lifecycle_record', 'id'), coalesce((SELECT max(id) FROM negotiation_lifecycle_record), 1));")
    w("")

    # ---- negotiation_resource_link (all four resources, REPRESENTATIVE_CONTACTED) ----
    w("-- negotiation_resource_link (resources 2351-2354, REPRESENTATIVE_CONTACTED)")
    w("INSERT INTO negotiation_resource_link (negotiation_id, resource_id, current_state)")
    w("VALUES")
    rows = []
    for i in range(count):
        nid = neg_uuid(i, offset)
        for rid in RESOURCES:
            rows.append(f"  ('{nid}', {rid}, 'REPRESENTATIVE_CONTACTED')")
    w(",\n".join(rows))
    w("ON CONFLICT DO NOTHING;")
    w("")

    # ---- negotiation_resource_lifecycle_record (SUBMITTED + REPRESENTATIVE_CONTACTED per resource) ----
    w("-- negotiation_resource_lifecycle_record (SUBMITTED then REPRESENTATIVE_CONTACTED per resource)")
    w("INSERT INTO negotiation_resource_lifecycle_record (id, created_by, creation_date, modified_date, modified_by, changed_to, negotiation_id, resource_id)")
    w("VALUES")
    rows = []
    for i in range(count):
        nid = neg_uuid(i, offset)
        base = res_lifecycle_base + i * 8
        for j, rid in enumerate(RESOURCES):
            rows.append(
                f"  ({base + j * 2 + 0}, 1, '2024-02-01 09:05:00', '2024-02-01 09:05:00', 1, "
                f"'SUBMITTED',                '{nid}', {rid})"
            )
            rows.append(
                f"  ({base + j * 2 + 1}, 2, '2024-02-01 10:00:00', '2024-02-01 10:00:00', 2, "
                f"'REPRESENTATIVE_CONTACTED', '{nid}', {rid})"
            )
    w(",\n".join(rows))
    w("ON CONFLICT DO NOTHING;")
    w("SELECT setval(pg_get_serial_sequence('negotiation_resource_lifecycle_record', 'id'), coalesce((SELECT max(id) FROM negotiation_resource_lifecycle_record), 1));")
    w("")

    # ---- posts (2 PUBLIC posts per negotiation) ----
    w("-- post (2 PUBLIC posts per negotiation; UUIDs are referenced by load-test.py post.added events)")
    w("INSERT INTO post (id, creation_date, modified_date, created_by, modified_by, type, text, negotiation_id)")
    w("VALUES")
    rows = []
    for i in range(count):
        nid = neg_uuid(i, offset)
        rows.append(
            f"  ('{post_uuid(i, 0, offset)}', '2024-02-01 09:10:00', '2024-02-01 09:10:00', 1, 1, 'PUBLIC', "
            f"'Load-test public post A for negotiation {i}.', '{nid}')"
        )
        rows.append(
            f"  ('{post_uuid(i, 1, offset)}', '2024-02-01 11:05:00', '2024-02-01 11:05:00', 2, 2, 'PUBLIC', "
            f"'Load-test public post B for negotiation {i}.', '{nid}')"
        )
    w(",\n".join(rows))
    w("ON CONFLICT DO NOTHING;")
    w("")

    return "\n".join(out) + "\n", neg_ids


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--count", type=int, default=50, help="number of negotiations to generate")
    parser.add_argument("--seed-offset", type=int, default=0,
                        help="batch offset; each distinct value yields a fresh non-overlapping batch")
    parser.add_argument("--out", default="scripts/load-seed.sql", help="output SQL file ('-' for stdout)")
    args = parser.parse_args()

    if args.count < 1:
        parser.error("--count must be >= 1")
    if args.seed_offset < 0:
        parser.error("--seed-offset must be >= 0")

    sql, neg_ids = generate(args.count, args.seed_offset)

    if args.out == "-":
        sys.stdout.write(sql)
    else:
        with open(args.out, "w", encoding="utf-8") as fh:
            fh.write(sql)
        # Negotiation ids to stdout so a caller can capture them.
        for nid in neg_ids:
            print(nid)
        print(f"# wrote {args.count} negotiations to {args.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
